#include <iostream>
using namespace std;
int main()
{
    int a = 10;
    int b = 20;
    cout << "a + b = " << a + b << endl;
    cout << "a - b = " << a - b << endl;
    cout << "a * b = " << a * b << endl;
    cout << "a / b = " << a / b << endl;
    cout << "a % b = " << a % b << endl;
    cout<<"5/2 = "<<5/(float)2<<endl;

    return 0;
}